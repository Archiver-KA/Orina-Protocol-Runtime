// Collection of all avatars for easy random selection
export const AVATAR_COMPONENTS = [
  Avatar1,
  Avatar2,
  Avatar6,
  Avatar14,
  Avatar17,
  Avatar18,
  Avatar19,
  Avatar20,
];

// Get a random avatar component
export function getRandomAvatar(seed?: number): React.ComponentType<{ className?: string }> {
  const index = seed !== undefined 
    ? seed % AVATAR_COMPONENTS.length 
    : Math.floor(Math.random() * AVATAR_COMPONENTS.length);
  return AVATAR_COMPONENTS[index];
}

// Get avatar by index
export function getAvatarByIndex(index: number): React.ComponentType<{ className?: string }> {
  return AVATAR_COMPONENTS[index % AVATAR_COMPONENTS.length];
}

// Get avatar by user ID (consistent mapping)
export function getAvatarByUserId(userId: string): React.ComponentType<{ className?: string }> {
  // Ensure userId is a string
  const userIdStr = String(userId || '');
  
  // Check if there's a random seed for this userId (from profile reset)
  const seedKey = `orina_avatar_seed_${userIdStr.toLowerCase()}`;
  const storedSeed = typeof window !== 'undefined' ? localStorage.getItem(seedKey) : null;
  
  if (storedSeed) {
    // Use the stored random seed
    const seed = parseInt(storedSeed, 10);
    const index = Math.abs(seed) % AVATAR_COMPONENTS.length;
    return AVATAR_COMPONENTS[index];
  }
  
  // Create a simple hash from userId to get consistent avatar
  let hash = 0;
  for (let i = 0; i < userIdStr.length; i++) {
    hash = ((hash << 5) - hash) + userIdStr.charCodeAt(i);
    hash = hash & hash; // Convert to 32-bit integer
  }
  const index = Math.abs(hash) % AVATAR_COMPONENTS.length;
  return AVATAR_COMPONENTS[index];
}

// Get avatar by username (consistent mapping)
export function getAvatarByUsername(username: string): React.ComponentType<{ className?: string }> {
  // Create a simple hash from username to get consistent avatar
  let hash = 0;
  for (let i = 0; i < username.length; i++) {
    hash = ((hash << 5) - hash) + username.charCodeAt(i);
    hash = hash & hash; // Convert to 32-bit integer
  }
  const index = Math.abs(hash) % AVATAR_COMPONENTS.length;
  return AVATAR_COMPONENTS[index];
}

/**
 * Get avatar component instance for userId
 * Returns a rendered avatar component ready to use
 */
export function getAvatarComponent(userId: string, className?: string): JSX.Element {
  const AvatarComponent = getAvatarByUserId(userId);
  return <AvatarComponent className={className} />;
}